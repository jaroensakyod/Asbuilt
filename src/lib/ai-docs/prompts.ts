export function invoicePrompt(o: { purpose: "bill" | "expense" | "delivery"; poNumbers?: string[]; poLines?: string[]; categories?: string[]; projects?: { id: string; name: string }[] }) {
  const out: string[] = [];
  if (o.purpose === "bill") out.push("อ่านใบกำกับภาษี/ใบแจ้งหนี้/ใบเสร็จของผู้ขายนี้ เพื่อบันทึกเป็นเจ้าหนี้");
  if (o.purpose === "expense") out.push("อ่านใบเสร็จ/บิลค่าใช้จ่ายนี้ (เงินสดย่อยหรือค่าใช้จ่ายหน้างาน) เลือก categoryGuess จากรายการหมวดที่ให้");
  if (o.purpose === "delivery") out.push("อ่านใบส่งของนี้ ต้องการรายการ จำนวน และหน่วยที่ส่งจริง");
  if (o.poNumbers?.length) out.push(`เลขที่ PO ที่เปิดอยู่ในระบบ (ใช้ช่วยอ่าน poNumber): ${o.poNumbers.slice(0, 40).join(", ")}`);
  if (o.poLines?.length) out.push(`รายการในใบสั่งซื้อ (ใช้ช่วยอ่านชื่อรายการ ห้ามคัดลอกจำนวนจากที่นี่):\n${o.poLines.map((l, i) => `${i + 1}. ${l}`).join("\n")}`);
  if (o.categories?.length) out.push(`หมวดค่าใช้จ่าย: ${o.categories.join(" | ")}`);
  if (o.projects?.length) out.push(`โครงการที่กำลังก่อสร้าง (ถ้าเอกสารระบุชื่อ/ที่อยู่ตรง ให้ใส่ใน projectHint): ${o.projects.slice(0, 40).map((p) => `${p.id} ${p.name}`).join("; ")}`);
  return out.join("\n\n");
}

